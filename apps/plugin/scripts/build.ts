import { mkdir, readdir, watch } from 'node:fs/promises'
import { join } from 'node:path'
import { parseArgs } from 'node:util'

// Build of the Obsidian plugin, from the plugin template of the author.
//
//   bun run build [--outdir <folder>]   a release build into `dist/`
//   bun run dev                         a build at each change of `src/`
//
// With the variable OBSIDIAN_VAULT_LOCATION, a development build is also
// copied into the plugins folder of that vault, with a `.hotreload` file.
// Use a test vault, never the real one, while the plugin is young.

const SRC = 'src'

/** Obsidian gives these modules at run time. They never enter the bundle. */
const EXTERNAL_MODULES = [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr'
]

const BANNER = `/*
THIS IS A GENERATED/BUNDLED FILE BY BUN.
If you want to view the source, please visit the github repository of this plugin.
*/
`

const { values } = parseArgs({
    args: Bun.argv.slice(2),
    options: {
        prod: { type: 'boolean', default: false },
        outdir: { type: 'string', default: 'dist' }
    },
    strict: true
})
const isProd = values.prod
const outDir = values.outdir

async function readPluginId(): Promise<string> {
    const manifest: unknown = await Bun.file('manifest.json').json()
    const id =
        typeof manifest === 'object' && manifest !== null && 'id' in manifest
            ? manifest.id
            : undefined
    if (typeof id !== 'string' || id === '') {
        throw new Error('manifest.json has no id')
    }
    return id
}

async function build(): Promise<void> {
    await mkdir(outDir, { recursive: true })
    await Bun.build({
        banner: BANNER,
        entrypoints: [`${SRC}/main.ts`],
        outdir: outDir,
        external: EXTERNAL_MODULES,
        format: 'cjs',
        target: 'node',
        minify: isProd,
        // 'none' and not `false`: an older Bun accepts the text form only.
        sourcemap: isProd ? 'none' : 'inline',
        throw: true
    })
    await Bun.write(join(outDir, 'manifest.json'), Bun.file('manifest.json'))
}

/** Copies a development build into the plugins folder of a vault. */
async function copyToVault(vault: string): Promise<void> {
    // The folder of a plugin has the id of the manifest.
    const pluginDir = join(vault, '.obsidian', 'plugins', await readPluginId())
    await mkdir(pluginDir, { recursive: true })
    for (const file of await readdir(outDir)) {
        await Bun.write(join(pluginDir, file), Bun.file(join(outDir, file)))
    }
    // The Hot Reload plugin loads the plugin again when this file exists.
    await Bun.write(join(pluginDir, '.hotreload'), '')
    console.error(`Copied the plugin to ${pluginDir}`)
}

async function buildForDevelopment(): Promise<void> {
    await build()
    const vault = process.env['OBSIDIAN_VAULT_LOCATION']
    if (vault !== undefined && vault !== '') {
        await copyToVault(vault)
    }
}

if (isProd) {
    await build()
} else {
    await buildForDevelopment()
    for await (const _event of watch(SRC, { recursive: true })) {
        try {
            await buildForDevelopment()
        } catch (error) {
            console.error(error)
        }
    }
}
